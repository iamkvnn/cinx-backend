package com.cinx.learning.catalog.application.mapper;

import com.cinx.learning.catalog.application.command.CreateCourseCommand;
import com.cinx.learning.catalog.application.command.UpdateCourseCommand;
import com.cinx.learning.catalog.application.query.CourseView;
import com.cinx.learning.catalog.application.query.UserView;
import com.cinx.learning.catalog.domain.Category;
import com.cinx.learning.catalog.domain.Course;
import com.cinx.learning.catalog.domain.CourseDraft;
import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.NullValuePropertyMappingStrategy;

@Mapper(componentModel = "spring")
public interface CourseMapper {
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "version", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "discountRate", ignore = true)
    @Mapping(target = "rating", ignore = true)
    @Mapping(target = "enrollmentCount", ignore = true)
    @Mapping(target = "instructorId", ignore = true)
    @Mapping(target = "isInSubscription", ignore = true)
    @Mapping(target = "accessModel", ignore = true)
    @Mapping(target = "subscriptionFeatureKey", ignore = true)
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "publishStatus", ignore = true)
    @Mapping(target = "categoryId", ignore = true)
    @Mapping(target = "images", ignore = true)
    @Mapping(target = "ratingCount", ignore = true)
    @Mapping(target = "outcomes", ignore = true)
    @Mapping(target = "publishedAt", ignore = true)
    @Mapping(target = "submittedAt", ignore = true)
    @Mapping(target = "archivedAt", ignore = true)
    @Mapping(target = "promoVideoKey", ignore = true)
    @Mapping(target = "promoVideoUrl", ignore = true)
    @Mapping(target = "promoVideoFileName", ignore = true)
    @Mapping(target = "promoVideoFileSize", ignore = true)
    @Mapping(target = "promoVideoDuration", ignore = true)
    @Mapping(target = "aiAssisted", ignore = true)
    Course toModel(CreateCourseCommand request);

    @BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "version", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "discountRate", ignore = true)
    @Mapping(target = "rating", ignore = true)
    @Mapping(target = "enrollmentCount", ignore = true)
    @Mapping(target = "instructorId", ignore = true)
    @Mapping(target = "isInSubscription", ignore = true)
    @Mapping(target = "accessModel", ignore = true)
    @Mapping(target = "subscriptionFeatureKey", ignore = true)
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "publishStatus", ignore = true)
    @Mapping(target = "categoryId", ignore = true)
    @Mapping(target = "images", ignore = true)
    @Mapping(target = "ratingCount", ignore = true)
    @Mapping(target = "publishedAt", ignore = true)
    @Mapping(target = "submittedAt", ignore = true)
    @Mapping(target = "archivedAt", ignore = true)
    @Mapping(target = "promoVideoKey", ignore = true)
    @Mapping(target = "promoVideoUrl", ignore = true)
    @Mapping(target = "promoVideoFileName", ignore = true)
    @Mapping(target = "promoVideoFileSize", ignore = true)
    @Mapping(target = "promoVideoDuration", ignore = true)
    // the AI label is only ever turned on, by the service
    @Mapping(target = "aiAssisted", ignore = true)
    void partialUpdate(@MappingTarget Course course, UpdateCourseCommand request);

    @Mapping(target = "id", ignore = true)
    @Mapping(target = "version", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "courseId", source = "id")
    CourseDraft toDraft(Course course);

    @BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "version", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "courseId", ignore = true)
    @Mapping(target = "discountRate", ignore = true)
    @Mapping(target = "categoryId", ignore = true)
    @Mapping(target = "aiAssisted", ignore = true)
    void partialUpdate(@MappingTarget CourseDraft draft, UpdateCourseCommand request);

    @Mapping(target = "id", ignore = true)
    @Mapping(target = "version", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "rating", ignore = true)
    @Mapping(target = "enrollmentCount", ignore = true)
    @Mapping(target = "instructorId", ignore = true)
    @Mapping(target = "isInSubscription", ignore = true)
    @Mapping(target = "accessModel", ignore = true)
    @Mapping(target = "subscriptionFeatureKey", ignore = true)
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "publishStatus", ignore = true)
    @Mapping(target = "images", ignore = true)
    @Mapping(target = "ratingCount", ignore = true)
    @Mapping(target = "publishedAt", ignore = true)
    @Mapping(target = "submittedAt", ignore = true)
    @Mapping(target = "archivedAt", ignore = true)
    @Mapping(target = "promoVideoKey", ignore = true)
    @Mapping(target = "promoVideoUrl", ignore = true)
    @Mapping(target = "promoVideoFileName", ignore = true)
    @Mapping(target = "promoVideoFileSize", ignore = true)
    @Mapping(target = "promoVideoDuration", ignore = true)
    void copyDraftToCourse(CourseDraft draft, @MappingTarget Course course);

    @Mapping(target = "instructor.id", source = "instructor.userId")
    @Mapping(target = "instructor.email", source = "instructor.email")
    @Mapping(target = "instructor.name", source = "instructor.name")
    @Mapping(target = "instructor.gender", source = "instructor.gender")
    @Mapping(target = "instructor.avatarUrl", source = "instructor.avatarUrl")
    @Mapping(target = "instructor.bio", source = "instructor.bio")
    @Mapping(target = "id", source = "course.id")
    @Mapping(target = "createdAt", source = "course.createdAt")
    @Mapping(target = "updatedAt", source = "course.updatedAt")
    @Mapping(target = "category", source = "category")
    CourseView toResponse(Course course, Category category, UserView instructor);

    @Mapping(target = "id", source = "course.id")
    @Mapping(target = "title", source = "draft.title")
    @Mapping(target = "description", source = "draft.description")
    @Mapping(target = "category", source = "category")
    @Mapping(target = "instructor.id", source = "instructor.userId")
    @Mapping(target = "instructor.email", source = "instructor.email")
    @Mapping(target = "instructor.name", source = "instructor.name")
    @Mapping(target = "instructor.gender", source = "instructor.gender")
    @Mapping(target = "instructor.avatarUrl", source = "instructor.avatarUrl")
    @Mapping(target = "instructor.bio", source = "instructor.bio")
    @Mapping(target = "images", source = "course.images")
    @Mapping(target = "price", source = "draft.price")
    @Mapping(target = "discountedPrice", source = "draft.discountedPrice")
    @Mapping(target = "discountRate", source = "draft.discountRate")
    @Mapping(target = "rating", source = "course.rating")
    @Mapping(target = "ratingCount", source = "course.ratingCount")
    @Mapping(target = "outcomes", source = "draft.outcomes")
    @Mapping(target = "enrollmentCount", source = "course.enrollmentCount")
    @Mapping(target = "isInSubscription", source = "draft.isInSubscription")
    @Mapping(target = "duration", source = "draft.duration")
    @Mapping(target = "hasCertificate", source = "draft.hasCertificate")
    @Mapping(target = "certificateTitle", source = "draft.certificateTitle")
    @Mapping(target = "status", source = "course.status")
    @Mapping(target = "publishStatus", source = "course.publishStatus")
    @Mapping(target = "createdAt", source = "draft.createdAt")
    @Mapping(target = "updatedAt", source = "draft.updatedAt")
    @Mapping(target = "publishedAt", source = "course.publishedAt")
    @Mapping(target = "submittedAt", source = "course.submittedAt")
    @Mapping(target = "archivedAt", source = "course.archivedAt")
    @Mapping(target = "aiAssisted", source = "draft.aiAssisted")
    CourseView toResponse(Course course, CourseDraft draft, Category category, UserView instructor);
}

